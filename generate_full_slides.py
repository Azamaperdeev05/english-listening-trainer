def render_slide(idx, s):
    img, draw = create_base_canvas(idx + 1, total_slides=len(slides_data), section_title=s.get("section", "ЖАЛПЫ ТІЛ БІЛІМІ"))
    
    # 1. Badge Pill
    badge_text = s.get("badge", "ТАҚЫРЫП")
    col = s.get("color", "#007AFF")
    bg = s.get("bg", "#EBF5FF")
    
    font_badge = get_font(26, "bold")
    bbox = font_badge.getbbox(badge_text)
    badge_w = (bbox[2] - bbox[0]) + 48
    draw.rounded_rectangle([134, 240, 134 + badge_w, 296], radius=16, fill=bg)
    draw.text((158, 252), badge_text, fill=col, font=font_badge)

    # 2. Watermark Number if present
    if "num" in s:
        draw.text((134, 320), s["num"], fill="#E5E5EA", font=get_font(100, "bold"))
        title_y = 440
    else:
        title_y = 330

    # Subtitle above title if present
    if "subtitle" in s:
        draw.text((134, 320), s["subtitle"], fill=col, font=get_font(32, "bold"))
        title_y = 380

    # 3. Main Title
    draw.text((134, title_y), s["title"], fill="#1C1C1E", font=get_font(56, "bold"), spacing=18)

    # Calculate offset for content based on title lines
    title_lines = s["title"].count("\n") + 1
    content_y = title_y + title_lines * 70 + 40

    # 4. Content Render Types:
    # Type A: Quote Slide
    if "quote" in s:
        quote_lines = wrap_text(s["quote"], get_font(42, "bold"), 720)
        card_h = len(quote_lines) * 64 + (180 if "tag" in s else 100)
        card_y2 = min(content_y + card_h, 1260)
        draw.rounded_rectangle([134, content_y, 946, card_y2], radius=30, fill="#F9F9FB", outline="#E5E5EA", width=1)
        draw.text((174, content_y + 45), "\n".join(quote_lines), fill="#1C1C1E", font=get_font(42, "bold"), spacing=22)
        
        # Tags below quote
        if "pills" in s:
            px = 134
            py = card_y2 + 40
            for p in s["pills"]:
                draw.rounded_rectangle([px, py, px + 246, py + 70], radius=18, fill=bg)
                draw.text((px + 36, py + 18), p, fill=col, font=get_font(28, "bold"))
                px += 276
        elif "tag" in s:
            draw.rounded_rectangle([180, card_y2 - 76, 560, card_y2 - 22], radius=16, fill=bg)
            draw.text((205, card_y2 - 64), s["tag"], fill=col, font=get_font(24, "bold"))

    # Type B: Items list (2-4 cards)
    elif "items" in s:
        y = content_y
        for item in s["items"]:
            if len(item) == 3:
                num, title, desc = item
                title = f"{num}. {title}"
            else:
                title, desc = item
            # Card
            t_lines = wrap_text(title, get_font(34, "bold"), 680)
            d_lines = wrap_text(desc, get_font(26, "regular"), 680)
            item_h = len(t_lines) * 44 + len(d_lines) * 36 + 48
            draw.rounded_rectangle([134, y, 946, y + item_h], radius=24, fill="#F9F9FB", outline="#E5E5EA", width=1)
            
            # Accent bar
            draw.rounded_rectangle([158, y + 24, 168, y + item_h - 24], radius=5, fill=col)
            
            draw.text((190, y + 24), "\n".join(t_lines), fill="#1C1C1E", font=get_font(34, "bold"), spacing=8)
            draw.text((190, y + 24 + len(t_lines) * 44 + 8), "\n".join(d_lines), fill="#636366", font=get_font(26, "regular"), spacing=6)
            y += item_h + 24

    # Type C: Methods list (Slide 06)
    elif "methods" in s:
        y = content_y
        for name, desc in s["methods"]:
            draw.rounded_rectangle([134, y, 946, y + 145], radius=22, fill="#F9F9FB", outline="#E5E5EA", width=1)
            draw.rounded_rectangle([158, y + 28, 168, y + 118], radius=5, fill=col)
            draw.text((190, y + 28), name, fill="#1C1C1E", font=get_font(34, "bold"))
            draw.text((190, y + 80), desc, fill="#636366", font=get_font(26, "regular"))
            y += 170

    # Type D: Branches list (Slide 07)
    elif "branches" in s:
        draw.rounded_rectangle([134, content_y, 946, content_y + 680], radius=30, fill="#F9F9FB", outline="#E5E5EA", width=1)
        draw.text((180, content_y + 40), "Зерттейтін басты өрістері:", fill="#8E8E93", font=get_font(28, "bold"))
        by = content_y + 110
        for b in s["branches"]:
            draw.rounded_rectangle([180, by + 12, 194, by + 26], radius=6, fill=col)
            draw.text((218, by), b, fill="#1C1C1E", font=get_font(30, "bold"))
            by += 105

    # Type E: Box with title, desc, tag
    elif "box_title" in s:
        b_lines = wrap_text(s.get("box_desc", ""), get_font(30, "regular"), 700)
        box_h = len(b_lines) * 44 + 230
        draw.rounded_rectangle([134, content_y, 946, content_y + box_h], radius=30, fill="#F9F9FB", outline="#E5E5EA", width=1)
        draw.text((180, content_y + 45), s["box_title"], fill="#1C1C1E", font=get_font(36, "bold"))
        draw.text((180, content_y + 115), "\n".join(b_lines), fill="#636366", font=get_font(30, "regular"), spacing=14)
        
        if "tag" in s:
            draw.rounded_rectangle([180, content_y + box_h - 70, 560, content_y + box_h - 20], radius=14, fill=bg)
            draw.text((205, content_y + box_h - 58), s["tag"], fill=col, font=get_font(24, "bold"))

    # 5. Live Speech Subtitle Bubble inside the card at bottom
    chunk = chunks[idx]
    clean_speech = chunk["text"]
    speech_lines = wrap_text(f"«{clean_speech}»", get_font(28, "medium"), 720)
    bubble_lines = speech_lines[:2] # display up to 2 lines
    bubble_h = len(bubble_lines) * 40 + 64
    by1 = 1640 - bubble_h
    by2 = 1650
    draw.rounded_rectangle([134, by1, 946, by2], radius=22, fill="#F9F9FB", outline="#E5E5EA", width=1)
    draw.text((168, by1 + 16), "ДАУЫС:", fill="#8E8E93", font=get_font(20, "bold"))
    draw.text((168, by1 + 46), "\n".join(bubble_lines), fill="#2C2C2E", font=get_font(26, "medium"), spacing=8)

    file_name = f"{OUTPUT_DIR}/slide_{idx+1:02d}.png"
    img.save(file_name)

print("Starting generation of all 59 slides...")
